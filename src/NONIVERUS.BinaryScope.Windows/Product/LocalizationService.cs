    public static string NormalizeLanguage(string? code)
    {
        if (string.IsNullOrWhiteSpace(code)) return "en";
        if (code.StartsWith("pt", StringComparison.OrdinalIgnoreCase)) return "pt";
        var candidate = code.Length >= 2 ? code[..2].ToLowerInvariant() : code.ToLowerInvariant();
        return Strings.ContainsKey(candidate) ? candidate : "en";
    }

    public static string T(string? languageCode, string key)
    {
        var language = NormalizeLanguage(languageCode);
        if (Strings.TryGetValue(language, out var localized) && localized.TryGetValue(key, out var value)) return value;
        if (Strings["en"].TryGetValue(key, out var fallback)) return fallback;
        return key;
    }

    public static string Format(string? languageCode, string key, params object[] args) =>
        string.Format(T(languageCode, key), args);
